import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {scanCatalog,verifyCatalogScan} from '../src/anti-slop-catalog-scan.js';
const catalog=JSON.parse(fs.readFileSync(new URL('../rules/anti-slop-catalog.json',import.meta.url),'utf8'));
const run=(s,p='fiction')=>scanCatalog(s,catalog,{profile:p});
test('detects vocabulary',()=>assert.ok(run('We must delve into the evidence.').findings.some(x=>x.term==='delve')));
test('does not match substring',()=>assert.equal(run('The undelved stone remains.').counts.total,0));
test('ignores fenced code',()=>assert.equal(run('```\ndelve\n```').counts.total,0));
test('ignores blockquote',()=>assert.equal(run('> delve into').counts.total,0));
test('does not alter original text',()=>{const s='A robust API.';assert.equal(s,'A robust API.');assert.equal(run(s).findings[0].action,'REVIEW_ONLY');});
test('context review for technical term',()=>assert.ok(run('A robust server.', 'technical-documentation').findings.some(x=>x.severity==='CONTEXT_REVIEW')));
test('financial profile same deterministic output',()=>assert.deepEqual(run('A crucial result.','financial-commentary'),run('A crucial result.','financial-commentary')));
test('Chinese profile scans English phrase',()=>assert.ok(run('这是一个 pivotal change.','chinese-longform').counts.total>0));
test('report verification',()=>{const t='The vibrant street.';assert.equal(verifyCatalogScan(t,catalog,run(t),{profile:'fiction'}).status,'VERIFIED');});
test('stale report rejected',()=>assert.throws(()=>verifyCatalogScan('Other text.',catalog,run('The vibrant street.'))));
test('tampering rejected',()=>{const r=run('The vibrant street.');r.counts.total=0;assert.throws(()=>verifyCatalogScan('The vibrant street.',catalog,r));});
test('invalid catalog rejected',()=>assert.throws(()=>scanCatalog('x',{vocabulary:[],phrases:[]})));
test('invalid text rejected',()=>assert.throws(()=>run(null)));
test('quoted phrase in inline code ignored',()=>assert.equal(run('Use `delve` as a token.').counts.total,0));
