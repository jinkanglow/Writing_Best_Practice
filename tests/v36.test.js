import test from 'node:test';
import assert from 'node:assert/strict';
import {sha256} from '../src/core.js';
import {prepareRevisionPlan} from '../src/revision-plan.js';
import {acceptRevision} from '../src/revision-acceptance.js';
import {readFileSync} from 'node:fs';
import {evaluateFinalGate,verifyFinalGate} from '../src/final-gate.js';
const before='A claim may rise.\n',after='A claim may rise.\n';
const anchors=[{id:'a',kind:'thesis',quote:'A claim may rise.'}];
const inventory=[{id:'a',kind:'qualification',quote:'may'}];
const rules=JSON.parse(readFileSync(new URL('../rules/anti-slop.json',import.meta.url),'utf8'));
const plan=prepareRevisionPlan(before,rules,anchors);
const planDecisions={planHash:plan.planHash,items:[]};
const {revisedText,...acceptance}=acceptRevision({before,plan,decisions:planDecisions,rules,anchors});
const base={before,after,anchors,inventory,acceptance,plan,planDecisions,rules};
test('missing acceptance fails closed',()=>assert.throws(()=>evaluateFinalGate({...base,acceptance:null}),/required/));
test('no skill contracts cannot be ready',()=>{const r=evaluateFinalGate(base);assert.equal(r.status,'INCOMPLETE');assert.ok(r.pending.includes('SKILL_CONTRACTS_NOT_PROVIDED'));});
test('stale acceptance fails',()=>assert.throws(()=>evaluateFinalGate({...base,after:'different'}),/mismatch/));
test('blocked acceptance blocks',()=>{assert.throws(()=>evaluateFinalGate({...base,acceptance:{...acceptance,status:'BLOCKED'}}),/mismatch|checksum/);});
test('report recomputation detects tampering',()=>{const r=evaluateFinalGate(base);assert.equal(verifyFinalGate(base,r).status,'REPORT_RECOMPUTED');assert.throws(()=>verifyFinalGate(base,{...r,status:'READY_FOR_HUMAN_RELEASE'}),/mismatch/);});
test('single skill fails closed',()=>assert.throws(()=>evaluateFinalGate({...base,primary:{version:'1.6',requirements:[]}}),/Both primary/));
test('tampered acceptance checksum fails',()=>assert.throws(()=>evaluateFinalGate({...base,acceptance:{...acceptance,reportHash:'bad'}}),/mismatch/));
test('empty editorial inventory is incomplete',()=>{const r=evaluateFinalGate({...base,inventory:[]});assert.equal(r.status,'INCOMPLETE');});
